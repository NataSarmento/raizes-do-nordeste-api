CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  senha_hash VARCHAR(100) NOT NULL,
  perfil VARCHAR(20) NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  consentimento_lgpd BOOLEAN NOT NULL DEFAULT FALSE,
  consentimento_lgpd_em TIMESTAMP,
  consentimento_fidelidade BOOLEAN NOT NULL DEFAULT FALSE,
  criado_em TIMESTAMP NOT NULL
);

CREATE TABLE unidades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  cidade VARCHAR(80) NOT NULL,
  ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE produtos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  descricao VARCHAR(300),
  categoria VARCHAR(60) NOT NULL,
  preco NUMERIC(12,2) NOT NULL,
  ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE estoques (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unidade_id BIGINT NOT NULL REFERENCES unidades(id),
  produto_id BIGINT NOT NULL REFERENCES produtos(id),
  quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
  CONSTRAINT uk_estoque_unidade_produto UNIQUE (unidade_id, produto_id)
);

CREATE TABLE movimentos_estoque (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unidade_id BIGINT NOT NULL REFERENCES unidades(id),
  produto_id BIGINT NOT NULL REFERENCES produtos(id),
  tipo VARCHAR(10) NOT NULL,
  quantidade INTEGER NOT NULL CHECK (quantidade > 0),
  motivo VARCHAR(200),
  pedido_id BIGINT,
  criado_em TIMESTAMP NOT NULL
);

CREATE TABLE promocoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(40) NOT NULL UNIQUE,
  descricao VARCHAR(200) NOT NULL,
  percentual_desconto NUMERIC(5,2) NOT NULL,
  valida_ate DATE,
  ativa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES usuarios(id),
  unidade_id BIGINT NOT NULL REFERENCES unidades(id),
  canal_pedido VARCHAR(10) NOT NULL,
  status VARCHAR(25) NOT NULL,
  forma_pagamento VARCHAR(20) NOT NULL,
  subtotal NUMERIC(12,2) NOT NULL,
  desconto NUMERIC(12,2) NOT NULL,
  total NUMERIC(12,2) NOT NULL,
  codigo_promocao VARCHAR(40),
  pontos_resgatados INTEGER NOT NULL DEFAULT 0,
  idempotency_key VARCHAR(80) UNIQUE,
  criado_em TIMESTAMP NOT NULL,
  atualizado_em TIMESTAMP NOT NULL
);
CREATE INDEX idx_pedidos_canal ON pedidos(canal_pedido);
CREATE INDEX idx_pedidos_status ON pedidos(status);
CREATE INDEX idx_pedidos_unidade ON pedidos(unidade_id);

CREATE TABLE itens_pedido (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
  produto_id BIGINT NOT NULL REFERENCES produtos(id),
  quantidade INTEGER NOT NULL CHECK (quantidade > 0),
  preco_unitario NUMERIC(12,2) NOT NULL
);

CREATE TABLE pagamentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
  status VARCHAR(15) NOT NULL,
  valor NUMERIC(12,2) NOT NULL,
  referencia_externa VARCHAR(80),
  mensagem VARCHAR(200),
  payload_gateway VARCHAR(1000),
  criado_em TIMESTAMP NOT NULL
);

CREATE TABLE movimentos_fidelidade (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  tipo VARCHAR(15) NOT NULL,
  pontos INTEGER NOT NULL,
  pedido_id BIGINT,
  criado_em TIMESTAMP NOT NULL
);

CREATE TABLE auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario VARCHAR(160) NOT NULL,
  acao VARCHAR(60) NOT NULL,
  entidade VARCHAR(60),
  entidade_id BIGINT,
  detalhe VARCHAR(500),
  criado_em TIMESTAMP NOT NULL
);
